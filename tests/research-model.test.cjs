const assert=require('node:assert/strict'),M=require('../dist/research-model.js'),D=require('../dist/data/performance.json'),S=require('../dist/data/supply-history.json'),F=require('../dist/data/research-models.json');
const b=M.baseline(D,S),o={...b,dailyIssuance:undefined,growth:0,horizon:12,target:1,lower:false},r=M.offset(o);
assert(Math.abs((r.required*b.fee*b.capture*b.allocation/b.price+b.burn)/b.issuance-1)<1e-9,'Threshold must meet offset target');
assert.equal(M.offset({...o,allocation:0}).required,null);
assert.equal(M.offset({...o,allocation:0,burn:b.issuance}).required,0);
assert.equal(M.offset({...o,volume:1,burn:0}).cross,null);
assert(M.offset({...o,lower:true}).required<r.required);
assert(M.offset({...o,price:b.price*2}).required>r.required);
assert(M.offset({...o,growth:.1}).endOffset>r.endOffset);
assert.throws(()=>M.offset({...o,price:0}));assert.throws(()=>M.offset({...o,capture:1.2}));
assert.equal(M.issuanceAt(100,3,true),100);assert.equal(M.issuanceAt(100,27,true),64);
const p={model:F.models.volume,price:b.price,growth:.1,market:0,horizon:6,lower:false,issuance:b.issuance,burn:b.burn,supply:b.supply},a=M.priceScenario(p);
assert.equal(a.rows[0].value,b.price);assert.deepEqual(a,M.priceScenario(p));
assert(M.priceScenario({...p,lower:true}).rows.at(-1).value>a.rows.at(-1).value);
assert(M.priceScenario({...p,market:.1}).rows.at(-1).value>a.rows.at(-1).value);
assert(a.rows.every(r=>r.low>0&&r.low<=r.high));
const weak={...p,model:F.models.buy};assert(!M.priceScenario(weak).supported);assert.deepEqual(M.priceScenario(weak).rows,M.priceScenario({...weak,growth:.5}).rows);
assert(Object.values(F.models).every(m=>m.validatedForecast===false&&m.holdouts>=10));
console.log('Research model checks passed.');

